const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const { PDFDocument } = require('pdf-lib')
const { _electron: electron } = require(process.env.PDFKING_PLAYWRIGHT || '/opt/homebrew/lib/node_modules/openclaw/node_modules/playwright-core')
;(async () => {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'pdfdock-keyboard-audit-'))
  const fixture = path.join(temporary, 'one-page.pdf')
  const pdf = await PDFDocument.create(); pdf.addPage([300, 400]); await fs.writeFile(fixture, await pdf.save())
  const env = { ...process.env, PDFKING_USE_BUILD: '1' }; delete env.ELECTRON_RUN_AS_NODE; delete env.VITE_DEV_SERVER_URL
  let app
  try {
    app = await electron.launch({ executablePath: require('electron'), args: ['.', `--user-data-dir=${path.join(temporary, 'profile')}`], env })
    const page = await app.firstWindow(); page.setDefaultTimeout(15000)
    const skip = page.getByRole('button', { name: 'Skip setup', exact: true }); await skip.waitFor(); await skip.click(); await skip.waitFor({ state: 'hidden' }); await page.locator('.onboarding-panel').waitFor({ state: 'detached' })
    const newDocument = page.getByRole('button', { name: 'New document', exact: true })
    await newDocument.focus(); await page.keyboard.press('Tab')
    assert.equal(await newDocument.evaluate(node => node === document.activeElement), false, 'Tab must advance from a Home button')
    await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click()
    const expand = page.getByRole('button', { name: 'Expand sidebar', exact: true })
    assert.equal(await expand.evaluate(node => node === document.activeElement), true, 'Collapsed sidebar must retain toggle focus')
    await expand.click()
    assert.equal(await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).evaluate(node => node === document.activeElement), true)
    await newDocument.click()
    const combos = page.locator('.new-doc-page-setup [role=combobox]')
    await combos.nth(0).click(); await page.keyboard.press('Tab')
    await page.getByRole('listbox').waitFor({ state: 'hidden' })
    assert.equal(await combos.nth(1).evaluate(node => node === document.activeElement), true, 'Tab must advance from page-size popup to orientation')
    await combos.nth(1).click(); await page.keyboard.press('Shift+Tab')
    await page.getByRole('listbox').waitFor({ state: 'hidden' })
    assert.equal(await combos.nth(0).evaluate(node => node === document.activeElement), true, 'Shift+Tab must return to the previous trigger')
    await combos.nth(0).click(); await page.keyboard.press('Escape')
    await page.waitForFunction(() => document.querySelector('.new-doc-page-setup [role=combobox]') === document.activeElement)
    await page.getByRole('button', { name: 'Close new document dialog', exact: true }).click(); await page.locator('[role=dialog]').waitFor({state:'detached'})
    await page.locator('.sidebar button[aria-label="Convert"]').click()
    await page.locator('.nav-subitem').filter({ hasText: /^PDF to JPG$/ }).click()
    await page.locator('.tool-studio-page input[type=file]').first().setInputFiles(fixture)
    await page.locator('.primary-action-btn').click()
    await page.locator('.output-save-controls').first().waitFor()
    const destination = path.join(temporary, 'saved-page.jpg')
    await app.evaluate(({ dialog }, destination) => { globalThis.__auditSaveCalls = 0; dialog.showSaveDialog = async () => { globalThis.__auditSaveCalls++; return { canceled: false, filePath: destination } } }, destination)

    await page.locator('.primary-action-btn').focus()
    await page.keyboard.press(process.platform === 'darwin' ? 'Meta+s' : 'Control+s')
    await page.waitForFunction(() => document.querySelector('.operation-message')?.textContent.startsWith('Saved ')).catch(async error => { console.log('SAVE DEBUG', await app.evaluate(() => globalThis.__auditSaveCalls), await page.evaluate(() => ({ body: document.body.innerText.slice(-1600), dialogs: [...document.querySelectorAll('[role=dialog]')].map(x=>x.textContent.slice(0,120)), focus: document.activeElement.outerHTML.slice(0,250) }))); throw error })
    assert.equal(await app.evaluate(() => globalThis.__auditSaveCalls), 1, 'Save shortcut should invoke the standalone output form exactly once')
    assert.ok((await fs.stat(destination)).size > 0)
    console.log('PASS audit keyboard UI IDs 16,20,21,22: native standalone shortcut save; Home Tab traversal; popup Tab/Shift+Tab/Escape; sidebar focus through collapse/expand.')
  } finally {
    if (app) { await app.evaluate(({ app }) => app.exit(0)).catch(() => {}); await app.close().catch(() => {}) }
    await fs.rm(temporary, { recursive: true, force: true })
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
