// Exercise real text and images; supply an external document and visible target.
const assert = require('node:assert/strict'), fs = require('node:fs/promises'), path = require('node:path'), os = require('node:os'), crypto = require('node:crypto')
const { _electron: electron } = require(process.env.PDFKING_PLAYWRIGHT || 'playwright-core')
const { captureUiBytes } = require('./electron-qa.cjs')
;(async () => {
  assert.ok(process.env.PDFKING_REAL_PDF && process.env.PDFKING_TEXT_TARGET, 'Set PDFKING_REAL_PDF and PDFKING_TEXT_TARGET (a visible first-page label)')
  const input = path.resolve(process.env.PDFKING_REAL_PDF), target = process.env.PDFKING_TEXT_TARGET
  const original = await fs.readFile(input), hash = data => crypto.createHash('sha256').update(data).digest('hex')
  const profile = await fs.mkdtemp(path.join(os.tmpdir(), 'pdf-dock-real-text-'))
  const env = { ...process.env, PDFKING_USE_BUILD: '1' }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.', `--user-data-dir=${profile}`], env })
  try {
    const page = await app.firstWindow(); page.setDefaultTimeout(20000)
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    const button = name => page.getByRole('button', { name, exact: true })
    const open = async file => {
      await page.reload(); await page.waitForSelector('button')
      if (await button('Skip setup').count()) await button('Skip setup').evaluate(node => node.click())
      await button('New document').first().click()
      await page.locator('.new-doc-backdrop input[type=file], .file-picker-backdrop input[type=file]').first().setInputFiles(file)
      await page.waitForSelector('canvas.is-rendered')
    }
    await open(input); await button('Edit text').click()
    const label = page.locator('.pdf-text-layer span').filter({ hasText: target }).first()
    await label.waitFor()
    const weight = await label.getAttribute('data-pdf-font-weight')
    await label.dblclick()
    const editor = page.getByRole('textbox', { name: 'Replace PDF paragraph', exact: true })
    const oldText = await editor.innerText(), newText = oldText.replace(target, 'TEST LABEL')
    assert.notEqual(oldText, newText)
    await editor.fill(newText)
    await fs.mkdir('tmp/issue-sweep',{recursive:true}); await page.locator('.pdf-editor-options').screenshot({path:'tmp/issue-sweep/inspector-text.png'})
    await button('Undo').click(); assert.equal(await editor.innerText(), oldText)
    await button('Redo').click(); assert.equal(await editor.innerText(), newText)
    await editor.press('Meta+A')
    await page.locator('.pdf-editor-options').getByRole('combobox', {name:'Font size',exact:true}).click()
    await page.getByRole('option', {name:'18 pt',exact:true}).click()
    assert.equal(await editor.isVisible(),true, 'Choosing a property must keep the text editing session active')
    await button('Undo').click()
    const resize = await page.locator('.pdf-text-live-handles .edge-e').boundingBox()
    assert.ok(resize, 'Active text must expose its resize handles')
    await page.mouse.move(resize.x + resize.width/2, resize.y + resize.height/2); await page.mouse.down(); await page.mouse.move(resize.x + resize.width/2 + 100, resize.y + resize.height/2, {steps:8}); await page.mouse.up()
    await editor.press('Meta+Enter')
    const preview = page.locator('.pdf-text-edit-preview').first()
    assert.equal(await preview.innerText(), newText)
    if (weight === '700') assert.ok(await preview.locator('.pdf-text-edit-content').evaluate(node => [...node.querySelectorAll('span')].every(span => Number(getComputedStyle(span).fontWeight) >= 600)), 'Bold source label must remain bold')
    await button('Add text').click()
    const canvas = page.locator('canvas[aria-label="PDF page 1"]'), box = await canvas.boundingBox()
    await page.mouse.click(box.x + box.width * .15, box.y + box.height * .87)
    const added = page.getByRole('textbox', { name: 'Add text to PDF', exact: true })
    await added.fill('Temporary text box'); await added.press('Meta+Enter')
    await button('Delete text box').click()
    assert.equal(await page.locator('.is-new-text.pdf-text-edit-preview').count(), 0)
    await button('Undo').click(); assert.equal(await page.locator('.is-new-text.pdf-text-edit-preview').count(), 1)
    await button('Redo').click(); assert.equal(await page.locator('.is-new-text.pdf-text-edit-preview').count(), 0)
    await button('Edit text').click(); await button('Apply changes').click()
    await page.waitForFunction(() => document.querySelector('.pdf-editor-status')?.textContent === 'Changes applied to the current document.')
    const output = Buffer.from(await captureUiBytes(page)), out = path.join(profile, 'text-edited.pdf'); await fs.writeFile(out, output)
    const pdfjs = await import('pdfjs-dist/legacy/build/pdf.mjs')
    const inspect = async bytes => {
      const task = pdfjs.getDocument({ data: new Uint8Array(bytes), standardFontDataUrl: path.resolve('node_modules/pdfjs-dist/standard_fonts') + '/', wasmUrl: path.resolve('node_modules/pdfjs-dist/wasm') + '/' })
      const document = await task.promise; const pages = []
      for (let n = 1; n <= document.numPages; n++) {
        const p = await document.getPage(n), content = await p.getTextContent(), ops = await p.getOperatorList()
        pages.push({ text: content.items.map(item => item.str || '').join(' ').replace(/\s+/g, ' ').trim(), images: ops.fnArray.filter(fn => [pdfjs.OPS.paintImageXObject, pdfjs.OPS.paintInlineImageXObject].includes(fn)).length })
      }
      await task.destroy(); return pages
    }
    const before = await inspect(original), after = await inspect(output)
    assert.equal(after.length, before.length)
    assert.ok(after[0].text.includes('TEST LABEL'))
    const escaped = target.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    assert.equal(new RegExp(`\\b${escaped}\\b`).test(after[0].text), false, 'Replaced original label must no longer be extractable')
    assert.equal(after[0].text.includes('Temporary text box'), false)
    for (let i = 1; i < before.length; i++) assert.deepEqual(after[i], before[i], `Unedited page ${i + 1} must retain text and embedded images`)
    await open(out)
    const reopened = page.locator('.pdf-text-layer span').filter({ hasText: 'TEST LABEL' }).first(); await reopened.waitFor()
    if (weight === '700') assert.equal(await reopened.getAttribute('data-pdf-font-weight'), '700')
    assert.equal(hash(await fs.readFile(input)), hash(original)); assert.deepEqual(errors, [])
    console.log('PASS real PDF: bold label replacement, active undo/redo, delete added text box without editing, committed bytes, source text removal, unedited page text/images retained, reopen and original hash.', { filename: path.basename(input), sourceWeight: weight, pages: before.length })
  } finally { await app.evaluate(({ app }) => app.exit(0)).catch(() => {}); await app.close().catch(() => {}); await fs.rm(profile, { recursive: true, force: true }) }
})().catch(error => { console.error(error); process.exitCode = 1 })
