// Run after npm run build and fixture generation. PDFKING_PLAYWRIGHT may point
// to an external playwright-core installation; tests use a disposable profile.
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { _electron: electron } = require(process.env.PDFKING_PLAYWRIGHT || 'playwright-core')
const { PDFDocument } = require('pdf-lib')
;(async () => {
  const profile = await fs.mkdtemp(path.join(os.tmpdir(), 'pdf-dock-sweep-'))
  const env = { ...process.env, PDFKING_USE_BUILD: '1' }
  delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.', `--user-data-dir=${profile}`], env })
  try {
    const page = await app.firstWindow()
    page.setDefaultTimeout(20000)
    app.process().stderr.on('data', chunk => fs.appendFile('/tmp/pdf-dock-electron-stderr.log', chunk).catch(() => {}))
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    const button = name => page.getByRole('button', { name, exact: true })
    const open = async file => {
      await page.reload()
      await page.waitForSelector('button')
      const skip = button('Skip setup')
      if (await skip.count()) await skip.click()
      await button('New document').first().click()
      await page.locator('.new-doc-backdrop input[type=file], .file-picker-backdrop input[type=file]').first().setInputFiles(file)
      await page.waitForSelector('canvas.is-rendered')
    }
    await open(path.resolve('tmp/sol-qa/master-original.pdf'))
    await button('Edit text').click()
    await page.locator('.pdf-text-layer span').filter({ hasText: 'Multiple lines stay' }).first().dblclick()
    const editor = page.getByRole('textbox', { name: 'Replace PDF paragraph', exact: true })
    await editor.fill('Typing history test')
    assert.equal(await button('Undo').isDisabled(), false)
    await button('Undo').click()
    assert.match(await editor.innerText(), /Multiple lines stay/)
    await button('Redo').click()
    assert.equal(await editor.innerText(), 'Typing history test')
    await editor.press('Meta+z')
    assert.match(await editor.innerText(), /Multiple lines stay/)
    await editor.press('Meta+Shift+z')
    assert.equal(await editor.innerText(), 'Typing history test')
    await editor.press('Meta+z')
    await editor.fill('New history branch')
    assert.equal(await button('Redo').isDisabled(), true)
    await editor.press('Meta+Enter')
    assert.equal(await page.locator('.pdf-text-edit-preview').innerText(), 'New history branch')
    await button('Undo').click()
    assert.equal(await page.locator('.pdf-text-edit-preview').count(), 0)
    await button('Redo').click()
    assert.equal(await page.locator('.pdf-text-edit-preview').innerText(), 'New history branch')
    await button('Apply changes').click()
    await page.waitForFunction(() => document.querySelector('.pdf-editor-status')?.textContent === 'Changes applied to the current document.')
    await button('Undo').click()
    assert.equal(await page.locator('.pdf-text-edit-preview').count(), 0)
    await button('Redo').click()
    await page.waitForSelector('canvas.is-rendered')
    console.log('PASS actual Electron: active text toolbar/keyboard history, redo invalidation, committed and applied edit undo/redo.')

    await open(path.resolve('tmp/sol-qa/master-original.pdf'))
    await button('Images').click()
    const imagePage = page.getByRole('spinbutton', { name: 'Current page', exact: true })
    await imagePage.fill('2'); await imagePage.press('Enter')
    const image = page.locator('.pdf-image-object[aria-label^="Image 0 on page 2"]')
    await image.waitFor()
    assert.equal(await page.locator('.pdf-image-object.selected').count(), 0, 'Images must not select themselves')
    await image.click()
    await page.locator('.image-inspector:not(.image-inspector-empty)').waitFor()
    const sourceSection = page.locator('.image-inspector-section').filter({ has: page.locator('summary span', { hasText: 'Source' }) })
    await sourceSection.locator('summary').click()
    assert.equal(await button('Add image').isVisible(), false)
    await sourceSection.locator('summary').click()
    assert.equal(await button('Add image').isVisible(), true)
    await button('Rotate image right').click()
    await button('Undo').click()
    await button('Redo').click()
    await fs.mkdir('tmp/issue-sweep', { recursive: true })
    for (const width of [1280, 760, 390]) {
      await page.setViewportSize({ width, height: 800 })
      await page.waitForTimeout(200)
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth) <= 2)
      const panel = page.locator('.image-inspector')
      assert.ok(await panel.evaluate(node => node.scrollWidth <= node.clientWidth + 2), 'Image inspector must fit its panel')
      await page.screenshot({ path: `tmp/issue-sweep/images-${width}.png` })
    }
    await page.setViewportSize({ width: 1280, height: 800 })
    console.log('PASS actual Electron: explicit image selection, collapsible sections, rotate/undo/redo and inspector width at 1280/760/390px.')

    const long = await PDFDocument.create()
    for (let i = 0; i < 60; i++) long.addPage(i % 2 ? [792, 612] : [612, 792]).drawText(`Page ${i + 1}`)
    const longPath = path.join(profile, 'long-compressed.pdf')
    await fs.writeFile(longPath, await long.save({ useObjectStreams: true }))
    await open(longPath)
    const viewer = page.locator('.pdf-viewer-page')
    const current = page.getByRole('spinbutton', { name: 'Current page', exact: true })
    await current.fill('30'); await current.press('Enter')
    await page.waitForSelector('canvas[aria-label="PDF page 30"].is-rendered')
    await viewer.hover()
    let previous = await viewer.evaluate(node => node.scrollTop)
    for (let i = 0; i < 8; i++) {
      await page.mouse.wheel(0, 220)
      await page.waitForTimeout(150)
      const top = await viewer.evaluate(node => node.scrollTop)
      assert.ok(top >= previous - 2, `Scrolling moved backwards: ${previous} -> ${top}`)
      previous = top
    }
    await page.waitForTimeout(600)
    assert.ok(Math.abs(await viewer.evaluate(node => node.scrollTop) - previous) < 3)
    await fs.mkdir('tmp/issue-sweep', { recursive: true })
    for (const width of [1280, 1024, 760, 390]) {
      await page.setViewportSize({ width, height: 800 })
      await page.waitForFunction(() => {
        const root = document.querySelector('.pdf-viewer-page')?.getBoundingClientRect()
        return root && [...document.querySelectorAll('canvas.is-rendered')].some(canvas => {
          const r = canvas.getBoundingClientRect()
          return canvas.width > 0 && r.bottom > root.top && r.top < root.bottom && r.right > root.left && r.left < root.right
        })
      })
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth) <= 2, `${width}px horizontal overflow`)
      assert.ok(await viewer.evaluate(node => node.clientWidth > 100))
      await page.screenshot({ path: `tmp/issue-sweep/editor-${width}.png` })
    }
    assert.deepEqual(errors, [])
    console.log('PASS actual Electron: compressed 60-page mixed-size PDF, monotonic scrolling, stable position and 1280/1024/760/390px layouts; no renderer errors.')
  } finally {
    // Test edits are intentionally unsaved; bypass the normal close prompt.
    await app.evaluate(({ app }) => app.exit(0)).catch(() => {})
    await app.close().catch(() => {})
    await fs.rm(profile, { recursive: true, force: true })
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
