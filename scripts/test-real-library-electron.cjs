const assert = require('node:assert/strict'), fs = require('node:fs/promises'), path = require('node:path'), os = require('node:os'), crypto = require('node:crypto')
const { _electron: electron } = require(process.env.PDFKING_PLAYWRIGHT || 'playwright-core')
;(async () => {
  const inputs = process.argv.slice(2).map(file => path.resolve(file))
  assert.ok(inputs.length >= 2, 'Pass at least two actual PDF paths')
  const originals = await Promise.all(inputs.map(file => fs.readFile(file))), hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex')
  const profile = await fs.mkdtemp(path.join(os.tmpdir(), 'pdf-dock-real-library-'))
  const env = { ...process.env, PDFKING_USE_BUILD: '1' }; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: ['.', `--user-data-dir=${profile}`], env })
  try {
    const page = await app.firstWindow(); page.setDefaultTimeout(20000)
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    const button = name => page.getByRole('button', { name, exact: true })
    await page.waitForSelector('button'); if (await button('Skip setup').count()) await button('Skip setup').evaluate(node => node.click())
    await app.evaluate(({ dialog }, filePaths) => {
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths })
      globalThis.__qaSaveDialogs = 0
      dialog.showSaveDialog = async () => { globalThis.__qaSaveDialogs++; return { canceled: true } }
    }, inputs)
    await button('Add PDFs').click()
    await page.waitForSelector('canvas.is-rendered')
    const records = () => page.evaluate(() => window.pdfKing.getRecentFiles())
    const initial = await records()
    assert.equal(initial.length, inputs.length, 'Every imported PDF must be stored before opening tabs')
    for (const file of inputs) assert.ok(initial.some(record => record.name === path.basename(file)))
    assert.equal(await page.locator('.workspace-tab').count() || await page.locator('[role=tab]').count(), inputs.length)
    await page.reload(); await page.waitForSelector('.home-file-row')
    const boxes = page.locator('.home-file-row input[type=checkbox]')
    for(let i=0;i<await boxes.count();i++) await boxes.nth(i).check()
    await page.getByRole('button',{name:new RegExp(`^Remove ${inputs.length} files$`)}).click()
    const confirmation = page.getByRole('dialog',{name:'Remove from library?',exact:true});await confirmation.waitFor()
    const dialogBounds = await confirmation.boundingBox();assert.ok(dialogBounds.width<=510&&dialogBounds.height<360, 'Bulk confirmation must stay compact')
    await page.keyboard.press('Escape');await confirmation.waitFor({state:'hidden'})
    assert.equal((await records()).length,inputs.length)
    await page.locator('.home-file-row').filter({hasText:path.basename(inputs.at(-1))}).dblclick();await page.waitForSelector('canvas.is-rendered')
    // An explicit Save must work even with automatic recent-file recording off.
    await page.evaluate(() => localStorage.setItem('pdfking-keep-recent', 'false'))
    await button('Add text').click()
    const canvas = page.locator('canvas[aria-label="PDF page 1"]'), bounds = await canvas.boundingBox()
    await page.mouse.click(bounds.x + bounds.width * .12, bounds.y + bounds.height * .82)
    const editor = page.getByRole('textbox', { name: 'Add text to PDF', exact: true })
    await editor.fill('Library save verification'); await editor.press('Meta+Enter')
    await button('Save changes').click()
    await page.waitForFunction(() => document.querySelector('.pdf-editor-status')?.textContent?.startsWith('Saved '))
    assert.equal(await app.evaluate(() => globalThis.__qaSaveDialogs), 0)
    const firstSave = await records()
    assert.equal(firstSave.length, initial.length, 'Saving must update the imported record without duplication')
    const changed = firstSave.find(record => record.name === path.basename(inputs.at(-1)))
    assert.ok(changed); assert.equal(changed.sourcePath, null)
    const data = Buffer.from(await page.evaluate(id => window.pdfKing.readRecentFile(id).then(data => Array.from(data)), changed.id))
    assert.notEqual(hash(data), hash(originals.at(-1)))
    await page.reload(); await page.waitForSelector('button')
    const row = page.locator('.home-file-row').filter({ hasText: path.basename(inputs.at(-1)) })
    await row.dblclick(); await page.waitForSelector('canvas.is-rendered')
    await page.locator('.pdf-text-layer span').filter({ hasText: 'Library save verification' }).first().waitFor()
    // Edit the reopened saved content and update the same library entry again.
    await button('Edit text').click()
    await page.locator('.pdf-text-layer span').filter({ hasText: 'Library save verification' }).first().dblclick()
    const replacement = page.getByRole('textbox', { name: 'Replace PDF paragraph', exact: true })
    await replacement.fill('Library save verified twice'); await replacement.press('Meta+Enter')
    await button('Save changes').click()
    await page.waitForFunction(() => document.querySelector('.pdf-editor-status')?.textContent?.startsWith('Saved '))
    assert.equal((await records()).length, initial.length)
    const twice = Buffer.from(await page.evaluate(id => window.pdfKing.readRecentFile(id).then(data => Array.from(data)), changed.id))
    assert.notEqual(hash(twice), hash(data))
    await page.reload(); await page.waitForSelector('button')
    await page.locator('.home-file-row').filter({ hasText: path.basename(inputs.at(-1)) }).dblclick()
    await page.waitForSelector('canvas.is-rendered')
    await page.waitForFunction(() => [...document.querySelectorAll('.pdf-text-layer span')].map(n=>n.textContent).join(' ').replace(/\s+/g,' ').includes('Library save verified twice'))
    for (let i=0;i<inputs.length;i++) assert.equal(hash(await fs.readFile(inputs[i])),hash(originals[i]))
    assert.equal(await app.evaluate(() => globalThis.__qaSaveDialogs), 0)
    assert.deepEqual(errors, [])
    console.log('PASS real PDFs: direct Home multi-import, one tab/record per file, explicit Save with auto-recents off, two save/reload/reopen cycles without duplicates or disk dialogs, original hashes unchanged.', inputs.map(file=>path.basename(file)))
  } finally { await app.evaluate(({ app }) => app.exit(0)).catch(()=>{}); await app.close().catch(()=>{}); await fs.rm(profile,{recursive:true,force:true}) }
})().catch(error=>{console.error(error);process.exitCode=1})
